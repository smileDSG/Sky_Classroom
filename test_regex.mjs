// 模拟几种 LLM 可能输出的格式，测试当前正则能否匹配

const testCases = [
  // 格式1: 标准格式（当前正则期望的）
  `案例1
名称：倾听技巧
详细描述：在沟通中，倾听是最重要的技巧之一。`,
  
  // 格式2: 无"案例"前缀
  `名称：倾听技巧
详细描述：在沟通中，倾听是最重要的技巧之一。`,
  
  // 格式3: 用数字编号
  `1. 倾听技巧
详细描述：在沟通中，倾听是最重要的技巧之一。`,
  
  // 格式4: 用-列表
  `- 倾听技巧
详细描述：在沟通中，倾听是最重要的技巧之一。`,
  
  // 格式5: 名称和描述在同一行
  `名称：倾听技巧  详细描述：在沟通中，倾听是最重要的技巧之一。`,
  
  // 格式6: 只有名称和冒号描述
  `倾听技巧：在沟通中，倾听是最重要的技巧之一。`,
  
  // 格式7: 案例X名称 连在一起
  `案例1名称：倾听技巧
详细描述：在沟通中，倾听是最重要的技巧之一。`,
];

const regex = /(?:案例\s*(\d+)|(?:^|\n)\s*(?:[-•]\s*)?)\s*名称[：:]\s*(.+?)\s*详细描述[：:]\s*(.+?)(?=(?:案例\s*\d+|(?:^|\n)\s*(?:[-•]\s*)?\s*名称)|$)/gi;

for (const tc of testCases) {
  const matches = [...tc.matchAll(regex)];
  console.log(`格式匹配数: ${matches.length} | 文本: ${tc.replace(/\n/g, '\n').substring(0, 60)}...`);
  for (const m of matches) {
    console.log(`  -> 名称:"${m[2]}" 描述:"${m[3].substring(0, 30)}..."`);
  }
}
