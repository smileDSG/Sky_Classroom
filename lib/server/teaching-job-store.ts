/**
 * Teaching Job Store — background job state management for AI teaching.
 *
 * Follows the same hybrid memory + disk pattern as classroom-job-store-hybrid.
 * Jobs are kept in memory for fast reads and flushed to disk periodically.
 */

import { promises as fs } from 'fs';
import path from 'path';
import { writeJsonFileAtomic } from '@/lib/server/classroom-storage';
import type { LessonPlan, LessonSection } from '@/lib/teaching/lesson-types';
import type { ContentChunk } from '@/lib/teaching/content-types';
import type { StructuredContent } from '@/lib/generation/classroom-content-agent';
import type { SectionFeedback, QuizResult } from '@/lib/teaching/adaptive-engine';
import type { TeachingGenerationPolicy } from '@/lib/teaching/personalization-policy';
import { createLogger } from '@/lib/logger';

const log = createLogger('TeachingJobStore');

const TEACHING_JOBS_DIR = path.join(process.cwd(), 'data', 'teaching-jobs');

async function ensureDir() {
  await fs.mkdir(TEACHING_JOBS_DIR, { recursive: true });
}

function jobFilePath(jobId: string) {
  return path.join(TEACHING_JOBS_DIR, `${jobId}.json`);
}

// ── Types ─────────────────────────────────────────────────────────

export type TeachingJobStatus = 'queued' | 'running' | 'succeeded' | 'failed' | 'cancelled';

export interface GeneratedSectionData {
  section: LessonSection;
  chunks: ContentChunk[];
  structured?: StructuredContent;
}

export interface TeachingJob {
  id: string;
  userId: string;
  topic: string;
  personalizationPolicy?: TeachingGenerationPolicy;
  status: TeachingJobStatus;
  /** Current step description */
  step: string;
  /** Progress 0-100 */
  progress: number;
  message: string;
  createdAt: string;
  updatedAt: string;
  startedAt?: string;
  completedAt?: string;

  /** The lesson plan generated by the planner */
  plan?: LessonPlan;
  /** Completed sections with content (accumulated during generation) */
  sections?: GeneratedSectionData[];
  /** Number of sections completed so far */
  sectionsCompleted?: number;
  /** Total number of sections in the plan */
  totalSections?: number;
  /** Whether the job is favorited by the user */
  isFavorited?: boolean;

  /** Section-level feedback collected during teaching */
  sectionFeedbacks?: SectionFeedback[];

  /** Quiz results collected during teaching */
  quizResults?: QuizResult[];

  error?: string;
}

// ── In-memory cache ───────────────────────────────────────────────

const inMemoryJobs = new Map<string, TeachingJob>();
const dirtyJobs = new Set<string>();
let flushTimer: ReturnType<typeof setInterval> | null = null;
let isFlushing = false;

const FLUSH_INTERVAL_MS = 5000;

function startFlushTimer() {
  if (flushTimer) return;
  flushTimer = setInterval(async () => {
    if (isFlushing || dirtyJobs.size === 0) return;
    isFlushing = true;
    const toFlush = [...dirtyJobs];
    dirtyJobs.clear();
    for (const jobId of toFlush) {
      const job = inMemoryJobs.get(jobId);
      if (job) {
        try {
          await writeJsonFileAtomic(jobFilePath(jobId), job);
        } catch {
          dirtyJobs.add(jobId);
        }
      }
    }
    isFlushing = false;
  }, FLUSH_INTERVAL_MS);
}

/** Mark stale jobs as failed if no progress for 30 min. */
function markStaleIfNeeded(job: TeachingJob): TeachingJob {
  if (job.status !== 'running') return job;
  const updatedAt = new Date(job.updatedAt).getTime();
  if (Date.now() - updatedAt > 30 * 60 * 1000) {
    return {
      ...job,
      status: 'failed',
      step: 'failed',
      message: 'Job appears stale (no progress update for 30 minutes)',
      error: 'Stale job: process may have restarted during generation',
      completedAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };
  }
  return job;
}

// ── CRUD ──────────────────────────────────────────────────────────

export async function createTeachingJob(
  jobId: string,
  userId: string,
  topic: string,
  personalizationPolicy?: TeachingGenerationPolicy,
): Promise<TeachingJob> {
  await ensureDir();
  const now = new Date().toISOString();
  const job: TeachingJob = {
    id: jobId,
    userId,
    topic,
    personalizationPolicy,
    status: 'queued',
    step: 'queued',
    progress: 0,
    message: '教案生成任务已创建',
    createdAt: now,
    updatedAt: now,
    sectionsCompleted: 0,
    totalSections: 0,
  };

  await writeJsonFileAtomic(jobFilePath(jobId), job);
  inMemoryJobs.set(jobId, job);
  return job;
}

export async function readTeachingJob(jobId: string): Promise<TeachingJob | null> {
  const cached = inMemoryJobs.get(jobId);
  if (cached) return markStaleIfNeeded(cached);

  try {
    const content = await fs.readFile(jobFilePath(jobId), 'utf-8');
    const job = JSON.parse(content) as TeachingJob;
    inMemoryJobs.set(jobId, job);
    return markStaleIfNeeded(job);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null;
    throw error;
  }
}

export async function updateTeachingJob(
  jobId: string,
  patch: Partial<TeachingJob>,
): Promise<TeachingJob> {
  const existing = await readTeachingJob(jobId);
  if (!existing) throw new Error(`Teaching job not found: ${jobId}`);

  const updated: TeachingJob = {
    ...existing,
    ...patch,
    updatedAt: new Date().toISOString(),
  };

  inMemoryJobs.set(jobId, updated);
  dirtyJobs.add(jobId);
  startFlushTimer();

  // Terminal states flush immediately
  if (patch.status === 'succeeded' || patch.status === 'failed' || patch.status === 'cancelled') {
    try {
      await writeJsonFileAtomic(jobFilePath(jobId), updated);
      dirtyJobs.delete(jobId);
    } catch {
      // Will retry on next flush
    }
  }

  return updated;
}

/** List all jobs for a given user, newest first. */
export async function listTeachingJobsByUser(userId: string): Promise<TeachingJob[]> {
  await ensureDir();
  try {
    const files = await fs.readdir(TEACHING_JOBS_DIR);
    const jobs: TeachingJob[] = [];

    for (const file of files) {
      if (!file.endsWith('.json')) continue;
      try {
        const content = await fs.readFile(path.join(TEACHING_JOBS_DIR, file), 'utf-8');
        const job = JSON.parse(content) as TeachingJob;
        if (job.userId === userId) {
          jobs.push(job);
        }
      } catch {
        // Skip corrupt files
      }
    }

    return jobs.sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());
  } catch {
    return [];
  }
}

/** Delete a teaching job file. */
export async function deleteTeachingJob(jobId: string): Promise<boolean> {
  try {
    await fs.unlink(jobFilePath(jobId));
    inMemoryJobs.delete(jobId);
    dirtyJobs.delete(jobId);
    return true;
  } catch {
    return false;
  }
}

// ── Status transition helpers ─────────────────────────────────────

export async function markTeachingJobRunning(jobId: string): Promise<TeachingJob> {
  return updateTeachingJob(jobId, {
    status: 'running',
    step: 'planning',
    message: '正在生成教案计划...',
    startedAt: new Date().toISOString(),
  });
}

export async function updateTeachingJobProgress(
  jobId: string,
  progress: {
    step?: string;
    progress?: number;
    message?: string;
    status?: TeachingJobStatus;
    plan?: LessonPlan;
    sectionsCompleted?: number;
    totalSections?: number;
    section?: GeneratedSectionData;
    isFavorited?: boolean;
  },
): Promise<TeachingJob> {
  const patch: Partial<TeachingJob> = {};

  if (progress.status !== undefined) {
    patch.status = progress.status;
  }
  if (progress.step !== undefined) patch.step = progress.step;
  if (progress.progress !== undefined) patch.progress = progress.progress;
  if (progress.message !== undefined) patch.message = progress.message;
  if (progress.plan) patch.plan = progress.plan;
  if (progress.sectionsCompleted !== undefined)
    patch.sectionsCompleted = progress.sectionsCompleted;
  if (progress.totalSections !== undefined) patch.totalSections = progress.totalSections;
  if (progress.isFavorited !== undefined) patch.isFavorited = progress.isFavorited;

  // Accumulate completed sections
  if (progress.section) {
    const existing = await readTeachingJob(jobId);
    if (existing) {
      patch.sections = [...(existing.sections ?? []), progress.section];
    }
  }

  return updateTeachingJob(jobId, patch);
}

export async function markTeachingJobSucceeded(jobId: string): Promise<TeachingJob> {
  const existing = await readTeachingJob(jobId);
  return updateTeachingJob(jobId, {
    status: 'succeeded',
    step: 'completed',
    progress: 100,
    message: '教案生成完成',
    completedAt: new Date().toISOString(),
    sectionsCompleted: existing?.sections?.length ?? existing?.sectionsCompleted ?? 0,
  });
}

export async function markTeachingJobFailed(jobId: string, error: string): Promise<TeachingJob> {
  return updateTeachingJob(jobId, {
    status: 'failed',
    step: 'failed',
    message: '教案生成失败',
    completedAt: new Date().toISOString(),
    error,
  });
}

export async function markTeachingJobCancelled(jobId: string): Promise<TeachingJob> {
  return updateTeachingJob(jobId, {
    status: 'cancelled',
    step: 'failed',
    message: '教案生成已取消',
    completedAt: new Date().toISOString(),
    error: '用户取消了生成',
  });
}
