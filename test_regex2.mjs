// 测试更宽松的正则

const cases = [
  // 格式A: 标准
  `案例1\n名称：倾听技巧\n详细描述：在沟通中，倾听是最重要的技巧之一。`,
  // 格式B: 数字编号
  `1. 倾听技巧\n详细描述：在沟通中，倾听是最重要的技巧之一。`,
  // 格式C: 列表
  `- 倾听技巧\n详细描述：在沟通中，倾听是最重要的技巧之一。`,
  // 格式D: 简化冒号
  `倾听技巧：在沟通中，倾听是最重要的技巧之一。`,
  // 格式E: markdown标题
  `**倾听技巧**\n在沟通中，倾听是最重要的技巧之一。`,
  // 格式F: 多段落描述
  `案例1\n名称：倾听技巧\n详细描述：在沟通中，倾听是最重要的技巧之一。\n需要专注和反馈。`,
];

// 新正则：支持多种格式
const newRegex = /(?:案例\s*\d+[\s:：]*|(?:^|\n)\s*(?:\d+[.．、]|[-•]\s*))?\s*(?:\*\*)?\s*(.+?)\s*(?:\*\*)?\s*[：:]\s*(.+?)(?=(?:\n\s*(?:案例\s*\d+|\d+[.．、]|[-•]|\*\*\s*[^\*]+\*\*)|\n\s*\n|$))/gi;

for (const tc of cases) {
  const matches = [...tc.matchAll(newRegex)];
  console.log(`匹配数: ${matches.length} | 文本: ${tc.replace(/\n/g, '\n').substring(0, 50)}...`);
  for (const m of matches) {
    console.log(`  -> 名称:"${m[1]}" 描述:"${m[2].substring(0, 30)}..."`);
  }
}
